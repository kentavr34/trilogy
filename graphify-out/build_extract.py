# ============ ГЛАВЫ ИТОГ-СБОРОК (парсинг) ============
POV_RE = re.compile(r'^\*\*·\s*(.+?)\s*·\*\*')
HEAD_RE = re.compile(r'^##\s+(Глава[^\n]*|Интерлюдия[^\n]*|Пролог[^\n]*|Эпилог[^\n]*)$')

def parse_itog(path_str, book_id, prefix):
    text = Path(path_str).read_text(encoding='utf-8').splitlines()
    idx = 0
    cur = None
    chapters = []
    for lineno, line in enumerate(text, 1):
        m = HEAD_RE.match(line.strip())
        if m:
            idx += 1
            cur = {'n': idx, 'title': m.group(1).strip(), 'line': lineno, 'pov': None}
            chapters.append(cur)
        elif cur and cur['pov'] is None:
            pm = POV_RE.match(line.strip())
            if pm: cur['pov'] = pm.group(1).strip()
    for ch in chapters:
        nid = f'{prefix}_g{ch["n"]:02d}'
        label = f'{ "Кн1" if prefix=="itog_kn1" else "Кн2" } [{ch["n"]:02d}] {ch["title"]}'
        desc = f'POV: {ch["pov"] or "—"}. Строка {ch["line"]} сборки ИТОГ 2026-08-03.'
        add_node(nid, label, 'document', path_str, desc, loc=f'line {ch["line"]}')
        add_edge(nid, book_id, 'references', 'EXTRACTED', 1.0, path_str)
        if ch['pov']:
            pov_id = 'pers_' + slug(ch['pov'])
            if pov_id in seen:
                add_edge(pov_id, nid, 'references', 'EXTRACTED', 1.0, path_str)
    return chapters

