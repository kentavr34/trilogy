TRANSLIT = {
    'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'zh','з':'z','и':'i','й':'y',
    'к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r','с':'s','т':'t','у':'u','ф':'f',
    'х':'h','ц':'c','ч':'ch','ш':'sh','щ':'sch','ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya',
}
def slug(s: str) -> str:
    s = s.lower()
    out = []
    for ch in s:
        if ch in TRANSLIT: out.append(TRANSLIT[ch])
        elif ch.isascii() and (ch.isalnum()): out.append(ch)
        else: out.append('_')
    r = re.sub(r'_+', '_', ''.join(out)).strip('_')
    return r or 'x'

def file_id(relpath: str) -> str:
    p = relpath.replace('\\', '/')
    if p.lower().endswith(('.md', '.txt', '.docx', '.json', '.py')):
        p = p.rsplit('.', 1)[0]
    return slug(p.replace('/', '_'))

nodes, edges, seen = [], [], set()

def add_node(nid, label, ftype, source, desc=None, loc=None):
    if nid in seen: return nid
    seen.add(nid)
    n = {'id': nid, 'label': label, 'file_type': ftype, 'source_file': source,
         'source_location': loc, 'source_url': None, 'captured_at': None,
         'author': None, 'contributor': None}
    if desc: n['description'] = desc
    nodes.append(n)
    return nid

def add_edge(src, dst, rel, conf, score, source):
    edges.append({'source': src, 'target': dst, 'relation': rel,
                  'confidence': conf, 'confidence_score': score,
                  'source_file': source, 'source_location': None, 'weight': 1.0})

