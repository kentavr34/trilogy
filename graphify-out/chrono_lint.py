# Канон структуры (обновлено 09.08.2026, приказ Кенана: вердикт-2 + рулетка времён):
#  Кн2 84→85 (интерлюдия «Канун» — глава Люцифера перед ч.6, блок D1)
#  Кн3: 84 юнита (пролог-тизер, +01b Смотритель, +06b/06c рулетка, +20e Тысяча девяносто — Ева в раме, 12.08)
STRUCT = {'1': {'chapters': 59, 'min_words': 75000},
          '2': {'chapters': 85, 'min_words': 75000},
          '3': {'chapters': 84, 'min_words': 75000}}

def check(path, key):
    errors, warns = [], []
    text = io.open(path, encoding='utf-8').read()
    lines = text.splitlines()
    for pat, books, why, white in FORBIDDEN:
        if key not in books:
            continue
        for i, ln in enumerate(lines, 1):
            if re.search(pat, ln, flags=re.IGNORECASE):
                if any(w.lower() in ln.lower() for w in white):
                    continue
                errors.append(f'ЗАПРЕЩЕНО [{why}] стр.{i}: …{ln.strip()[:90]}…  /{pat}/')
    for pat, book, mn, why in REQUIRED:
        if book != key:
            continue
        n = len(re.findall(pat, text))
        if n < mn:
            errors.append(f'ОТСУТСТВУЕТ [{why}]: /{pat}/ найдено {n}, нужно ≥{mn}')
    st = STRUCT[key]
    nch = len(re.findall(r'^## (Глава|Интерлюдия|Пролог|Эпилог)', text, flags=re.M))
    if nch != st['chapters']:
        errors.append(f'СТРУКТУРА: глав {nch}, канон {st["chapters"]}')
    words = len(re.findall(r'[А-Яа-яЁёA-Za-z]+(?:-[А-Яа-яЁёA-Za-z]+)*', text))
    if words < st['min_words']:
        errors.append(f'ОБЪЁМ: {words} слов < {st["min_words"]}')
    return errors, words, nch

def main():
    total_err = 0
    for path, key, name in ((K1, '1', 'КНИГА I'), (K2, '2', 'КНИГА II'), (K3, '3', 'КНИГА III')):
        if not path.exists():
            print(f'!! {name}: файл не найден: {path}')
            total_err += 1
            continue
        errs, words, nch = check(path, key)
        status = 'OK' if not errs else f'FAIL ({len(errs)})'
        print(f'[{status}] {name}: глав {nch}, слов {words}')
        for e in errs:
            print('   ', e)
        total_err += len(errs)
    if total_err == 0:
        print('ХРОНОЛИНТЕР: канон соблюдён полностью.')
        return 0
    print(f'ХРОНОЛИНТЕР: {total_err} нарушений канона — исправить до зеркалирования!')
    return 1

if __name__ == '__main__':
    sys.exit(main())
